"""Audit our extracted numbers against the ORIGINAL SEC filings.

The app reads numbers from the SEC's JSON API. This script does not trust
that API: for every number the app shows, it downloads the actual 10-K
document from sec.gov and looks for the same number printed next to the
matching line label (for example "Total net sales ... 416,161").

It also checks, independently of the API:
  * each filing's form type and filing date (from the filing's own index page),
  * the arithmetic of growth / margin / free cash flow,
  * reporting periods (lengths, overlaps, gaps),
  * a 10-Q cross-check: 9-month figures + implied Q4 vs the 10-K year,
  * blank cells: does the filing itself show a number the API lacks?

Run:   python scripts/verify_filings.py            (uses the cache in .sec_cache/)
       python scripts/verify_filings.py --refresh  (re-download everything)

Writes reports/verification_report.md and reports/verification_details.csv.
Downloads are cached on disk so the SEC is not asked for the same file twice.
"""

import argparse
import csv
import html
import json
import re
import sys
from datetime import date
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

import financials as fin  # noqa: E402
import sec_client  # noqa: E402

TICKERS = ["AAPL", "MSFT", "NVDA", "VRT", "GOOGL"]
CACHE = ROOT / ".sec_cache"
REPORTS = ROOT / "reports"

# How each metric is labelled in a company's own financial statements.
LABELS = {
    "revenue": r"total net sales|net sales|total revenues?|revenues?|net revenues?",
    "operating_income": r"operating income|income from operations|operating profit|operating \(loss\) income|operating loss",
    "operating_cash_flow": r"net cash (?:provided by|generated by|from|used in|\(used in\)|provided by \(used in\))[^.]{0,50}operating activities|cash generated by operating activities|net cash from operations|net cash provided by operations",
    "capex": r"payments for acquisition of property|purchases? (?:related to|of) property|capital expenditures|additions to property|payments to acquire|purchases of property|property and equipment",
    "diluted_shares": r"diluted|weighted[- ]average|shares used",
}
WINDOW = 300  # characters after the label in which the number must appear


# ---------------------------------------------------------------------------
# Downloading with a disk cache
# ---------------------------------------------------------------------------
def cached(path: Path, loader, refresh: bool, binary_json: bool = False):
    if path.exists() and not refresh:
        text = path.read_text()
        return json.loads(text) if binary_json else text
    value = loader()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value) if binary_json else value)
    return value


def html_to_text(raw: str) -> str:
    raw = re.sub(r"<(script|style)\b.*?</\1>", " ", raw, flags=re.S | re.I)
    text = html.unescape(re.sub(r"<[^>]+>", " ", raw)).replace("\xa0", " ")
    return re.sub(r"\s+", " ", text)


def accn_dir(cik: int, accn: str) -> str:
    return f"https://www.sec.gov/Archives/edgar/data/{cik}/{accn.replace('-', '')}"


def filing_meta(cik: int, accn: str, refresh: bool) -> Dict[str, str]:
    """Form type, filing date and period of report from the filing's own index page."""

    def load():
        raw = sec_client.fetch_text(f"{accn_dir(cik, accn)}/{accn}-index.htm")
        text = html_to_text(raw)
        pick = lambda pat: (re.search(pat, text) or [None, ""])[1]  # noqa: E731
        return json.dumps({
            "form": pick(r"Form (10-K/A|10-K|10-Q|8-K|\S+)"),
            "filed": pick(r"Filing Date (\d{4}-\d{2}-\d{2})"),
            "period": pick(r"Period of Report (\d{4}-\d{2}-\d{2})"),
        })

    return json.loads(cached(CACHE / "meta" / f"{accn}.json", load, refresh))


def filing_text(cik: int, accn: str, refresh: bool) -> Tuple[str, str]:
    """Plain text of the filing's main document, and its URL."""

    def load():
        listing = sec_client.fetch_json(f"{accn_dir(cik, accn)}/index.json")
        docs = [i for i in listing["directory"]["item"]
                if i["name"].lower().endswith(".htm") and not re.match(r"R\d", i["name"])]
        main = max(docs, key=lambda i: int(i.get("size") or 0))["name"]
        return json.dumps({"url": f"{accn_dir(cik, accn)}/{main}",
                           "text": html_to_text(sec_client.fetch_text(f"{accn_dir(cik, accn)}/{main}"))})

    data = json.loads(cached(CACHE / "filings" / f"{accn}.json", load, refresh))
    return data["text"], data["url"]


# ---------------------------------------------------------------------------
# Finding a number in a filing
# ---------------------------------------------------------------------------
def display_forms(value: float) -> List[str]:
    """Ways a filing might print this value: in millions, thousands or dollars."""
    v = abs(value)
    forms = []
    for scale, decimals in ((1e6, 0), (1e6, 1), (1e3, 0), (1, 0)):
        scaled = v / scale
        if abs(scaled - round(scaled, decimals)) < 1e-6:  # exactly representable at that precision
            forms.append(f"{scaled:,.{decimals}f}")
    return list(dict.fromkeys(forms))


# A "column" is either a number or a lone dash (statements print zero as a dash).
NUMBER_TOKEN = re.compile(r"(?<![\d,.])\d[\d,]*(?:\.\d+)?(?![\d,])|(?<=\s)[—–](?=\s)")


def check_number(text: str, metric: str, value: float) -> Tuple[str, str, List[int]]:
    """Return (status, evidence, columns).

    status: NEAR_LABEL / ELSEWHERE / NOT_FOUND.
    columns: for each place the number is printed right after a matching label,
    its position (0 = first number printed after the label) among the numbers
    that follow, i.e. which year-column it sits in.
    """
    if value == 0:  # statements print zero as a dash: "Revenues $ — $ — $ —"
        for label in re.finditer(LABELS[metric], text, flags=re.I):
            if re.match(r"[\s$]*[—–-](?!\w)", text[label.end(): label.end() + 20]):
                return "NEAR_LABEL", f"...{text[label.start(): label.end() + 20]} (a dash = zero)", [0]
    forms = display_forms(value)
    patterns = [re.compile(r"(?<![\d,.])" + re.escape(f) + r"(?![\d,]|\.\d)") for f in forms]
    evidence, columns = "", []
    for label in re.finditer(LABELS[metric], text, flags=re.I):
        window = text[label.end(): label.end() + WINDOW]
        tokens = NUMBER_TOKEN.findall(window)
        for pattern in patterns:
            hit = pattern.search(window)
            if hit:
                if not evidence:
                    evidence = f"...{text[label.start(): label.end() + hit.end()][-110:]}"
                columns.extend(i for i, tok in enumerate(tokens) if tok == hit.group(0))
    if evidence:
        return "NEAR_LABEL", evidence, sorted(set(columns))
    for pattern in patterns:
        hit = pattern.search(text)
        if hit:
            return "ELSEWHERE", f"number {hit.group(0)} appears, but not next to a matching label", []
    return "NOT_FOUND", "", []


GAP_LABELS = dict(LABELS, **{
    "capex": r"purchases related to property and equipment|payments for acquisition of property|payments to acquire property|purchases of property|additions to property",
    "diluted_shares": r"number of shares used in per share computation|weighted[- ]average (?:common )?shares[^.]{0,60}diluted|diluted weighted[- ]average",
    "operating_income": r"operating income|income from operations|operating profit",
})


def snippet_for_label(text: str, metric: str, width: int = 200) -> str:
    """The first statement line with this label and a number, to read what the filing prints."""
    for hit in re.finditer(f"(?:{GAP_LABELS[metric]})[^0-9]{{0,60}}[(\\s$]*\\d[\\d,]{{2,}}", text, flags=re.I):
        return text[hit.start(): hit.start() + width]
    return ""


# ---------------------------------------------------------------------------
# One company
# ---------------------------------------------------------------------------
def nine_month_fact(facts: Dict[str, Any], metric: str, fy_start: date, fy_end: date) -> Optional[Dict[str, Any]]:
    """Original 10-Q year-to-date (about 9 months) fact for the fiscal year starting `fy_start`."""
    spec = fin.METRICS[metric]
    us = facts.get("facts", {}).get("us-gaap", {})
    for concept in spec.concepts:
        best = None
        for e in us.get(concept, {}).get("units", {}).get(spec.unit, []):
            if e.get("form") != "10-Q" or not e.get("start"):
                continue
            start, end = date.fromisoformat(e["start"]), date.fromisoformat(e["end"])
            if start == fy_start and 250 <= (end - start).days <= 290 and end <= fy_end:
                if best is None or e["filed"] < best["filed"]:  # the ORIGINAL 10-Q, not a later comparative
                    best = dict(e, concept=concept)
        if best:
            return best
    return None


def audit_company(ticker: str, cik: int, facts: Dict[str, Any], refresh: bool, details: List[dict]) -> Dict[str, Any]:
    result = fin.build_annual_result(facts, max_years=10)
    table, sources = result.table, result.sources
    out: Dict[str, Any] = {"ticker": ticker, "cik": cik, "name": result.company_name, "result": result,
                           "counts": {"NEAR_LABEL": 0, "ELSEWHERE": 0, "NOT_FOUND": 0, "ERROR": 0},
                           "meta_mismatch": [], "filings": {}, "gaps": [], "derived_errors": [],
                           "period_issues": [], "tenq": [], "restated": [], "matrix": {},
                           "columns": {"ok": 0, "off": 0, "na": 0}, "column_off": []}

    # ---- 1. every reported value vs the filing text -----------------------
    for accn, group in sources.groupby("accession_number"):
        try:
            meta = filing_meta(cik, accn, refresh)
            text, url = filing_text(cik, accn, refresh)
        except sec_client.SecError as exc:
            out["counts"]["ERROR"] += len(group)
            out["filings"][accn] = {"error": str(exc)}
            continue
        out["filings"][accn] = dict(meta, url=url, index=f"{accn_dir(cik, accn)}/{accn}-index.htm")
        first = group.iloc[0]
        if meta["form"] != first["form"] or meta["filed"] != str(first["filed"]):
            out["meta_mismatch"].append(f"{accn}: API says {first['form']} filed {first['filed']}, "
                                        f"filing page says {meta['form']} filed {meta['filed']}")
        head = text[:200000].upper()  # the first part is hidden XBRL header text
        if not (re.search(r"FORM\s+10-K", head) or "ANNUAL REPORT PURSUANT" in head):
            out["meta_mismatch"].append(f"{accn}: document text does not look like a 10-K")

        period_end = date.fromisoformat(meta["period"]) if meta["period"] else None
        facts_in_filing = []
        for _, src in group.iterrows():
            metric = next(k for k, s in fin.METRICS.items() if s.label == src["metric"])
            status, evidence, columns = check_number(text, metric, src["value"])
            out["counts"][status] += 1
            out["matrix"][(src["period_end"], metric)] = status
            rank = round((period_end - src["period_end"]).days / 365.25) if period_end else None
            facts_in_filing.append((src, rank, columns, len(details)))
            details.append({"ticker": ticker, "metric": src["metric"], "period_start": src["period_start"],
                            "period_end": src["period_end"], "value": src["value"], "unit": src["unit"],
                            "sec_concept": src["sec_concept"], "form": src["form"], "filed": src["filed"],
                            "accession_number": accn, "filing_url": url, "check": status, "evidence": evidence,
                            "columns_found": columns, "years_before_filing_period": rank, "year_column_check": ""})
            if pd.notna(src["first_reported_value"]) and src["first_reported_value"] != src["value"]:
                out["restated"].append(f"{src['metric']} FY end {src['period_end']}: first filed "
                                       f"{src['first_filed']} = {src['first_reported_value']:,.0f}; "
                                       f"now {src['value']:,.0f} ({accn})")

        # Year-column check. Statements show up to 3 years side by side, newest first
        # (Apple, Microsoft...) or oldest first (Alphabet). Pick the orientation that fits
        # most numbers in this filing, then flag any number sitting in the wrong year column.
        candidates = [(src, rank, cols, i) for src, rank, cols, i in facts_in_filing
                      if rank is not None and 0 <= rank <= 2 and cols]
        newest_first = sum(rank in cols for _, rank, cols, _ in candidates)
        oldest_first = sum((2 - rank) in cols for _, rank, cols, _ in candidates)
        use_newest_first = newest_first >= oldest_first
        out["filings"][accn]["column_order"] = "newest first" if use_newest_first else "oldest first"
        for src, rank, cols, i in candidates:
            expected = rank if use_newest_first else 2 - rank
            ok = expected in cols
            # Alphabet prints diluted shares in a per-class table (Class A, B, C, Total), so
            # "column N" does not mean "year N" there. Those are confirmed by hand instead.
            not_applicable = (not ok) and src["metric"].startswith("Diluted") and all(c >= 3 for c in cols)
            if ok:
                details[i]["year_column_check"] = "COLUMN_OK"
            elif not_applicable:
                details[i]["year_column_check"] = "COLUMN_NOT_APPLICABLE (multi-class share table)"
            else:
                details[i]["year_column_check"] = f"COLUMN_OFF (expected {expected}, found {cols})"
            out["columns"]["ok" if ok else ("na" if not_applicable else "off")] += 1
            if not ok and not not_applicable:
                out["column_off"].append(f"{src['metric']} FY end {src['period_end']} in {accn}: expected column "
                                         f"{expected}, found {cols}")

    # ---- 2. arithmetic of derived columns, recomputed independently --------
    rows = table.to_dict("records")
    full_rows = fin.build_annual_result(facts, max_years=1000).table.to_dict("records")
    shown_ends = {r["period_end"] for r in rows}
    for i, r in enumerate(full_rows):
        if r["period_end"] not in shown_ends:
            continue
        if pd.notna(r["operating_income"]) and pd.notna(r["revenue"]) and r["revenue"] > 0:
            if abs(r["operating_margin"] - r["operating_income"] / r["revenue"]) > 1e-12:
                out["derived_errors"].append(f"margin {r['period_end']}")
        if pd.notna(r["operating_cash_flow"]) and pd.notna(r["capex"]):
            if abs(r["free_cash_flow"] - (r["operating_cash_flow"] - r["capex"])) > 0.5:
                out["derived_errors"].append(f"FCF {r['period_end']}")
        elif pd.notna(r["free_cash_flow"]):
            out["derived_errors"].append(f"FCF present without both inputs {r['period_end']}")
        prev = next((p for p in reversed(full_rows[:i]) if 350 <= (r["period_end"] - p["period_end"]).days <= 380), None)
        if prev is not None and pd.notna(r["revenue"]) and pd.notna(prev["revenue"]) and prev["revenue"] > 0:
            if abs(r["revenue_growth"] - (r["revenue"] / prev["revenue"] - 1)) > 1e-12:
                out["derived_errors"].append(f"growth {r['period_end']}")
        elif pd.notna(r["revenue_growth"]):
            out["derived_errors"].append(f"growth present without consecutive prior year {r['period_end']}")

    # ---- 3. reporting periods ----------------------------------------------
    previous = None
    for r in rows:
        if not 350 <= r["days"] <= 380:
            out["period_issues"].append(f"{r['period_end']}: length {r['days']} days")
        if previous and r["period_start"] <= previous["period_end"]:
            out["period_issues"].append(f"{r['period_end']}: overlaps {previous['period_end']}")
        if previous and not 350 <= (r["period_end"] - previous["period_end"]).days <= 380:
            out["period_issues"].append(f"{previous['period_end']} -> {r['period_end']}: "
                                        f"{(r['period_end'] - previous['period_end']).days} days apart")
        previous = r

    # ---- 4. blank cells: does the filing itself print a number? -----------
    columns = {"revenue": "revenue", "operating_income": "operating_income",
               "operating_cash_flow": "operating_cash_flow", "capex": "capex", "diluted_shares": "diluted_shares"}
    for r in rows[-8:]:
        for metric, col in columns.items():
            if pd.isna(r[col]):
                accns = sources[sources["period_end"] == r["period_end"]]
                if accns.empty:
                    continue
                accn = accns.sort_values("filed").iloc[-1]["accession_number"]
                try:
                    text, url = filing_text(cik, accn, refresh)
                except sec_client.SecError:
                    continue
                out["gaps"].append({"period_end": r["period_end"], "metric": metric, "accn": accn, "url": url,
                                    "snippet": snippet_for_label(text, metric)})

    # ---- 5. 10-Q cross-check for the latest fiscal year ---------------------
    if rows:
        latest = rows[-1]
        for metric in ("revenue", "operating_income", "operating_cash_flow"):
            fy_value = latest[metric]
            if pd.isna(fy_value):
                continue
            q = nine_month_fact(facts, metric, latest["period_start"], latest["period_end"])
            if not q:
                out["tenq"].append({"metric": metric, "note": "no 9-month 10-Q fact found"})
                continue
            entry = {"metric": metric, "fy_end": latest["period_end"], "fy_value": fy_value, "ytd9": q["val"],
                     "implied_q4": fy_value - q["val"], "accn": q["accn"], "filed": q["filed"], "ytd_end": q["end"]}
            try:
                text, url = filing_text(cik, q["accn"], refresh)
                meta = filing_meta(cik, q["accn"], refresh)
                entry["check"], _, _ = check_number(text, metric, q["val"])
                entry["form_on_filing_page"] = meta["form"]
                entry["url"] = url
            except sec_client.SecError as exc:
                entry["check"] = f"ERROR {exc}"
            share = entry["implied_q4"] / fy_value if fy_value else None
            entry["sane"] = bool(entry["implied_q4"] > 0 and share is not None and 0.10 <= share <= 0.45) \
                if metric == "revenue" else entry["ytd9"] != fy_value
            out["tenq"].append(entry)
    return out


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------
MARK = {"NEAR_LABEL": "✓", "ELSEWHERE": "~", "NOT_FOUND": "✗", "ERROR": "?"}


def money(v: float, shares: bool = False) -> str:
    if pd.isna(v):
        return "—"
    return f"{v / 1e6:,.1f}" if shares else f"{v / 1e6:,.0f}"


def write_report(audits: List[Dict[str, Any]], path: Path) -> None:
    L: List[str] = [f"# Multibagger Hunter — SEC verification report", "",
                    f"Generated {date.today()}. Every reported value was searched for in the original 10-K document "
                    f"on sec.gov, next to its line label. ✓ = found next to the right label · ~ = number appears but "
                    f"not next to a label · ✗ = not found · — = blank in the app.", ""]
    L += ["## Summary", "", "| Company | Values checked | ✓ near label | ~ elsewhere | ✗ not found | Filing-page mismatches | Arithmetic errors | Period issues | Year-column OK / off / n.a. |",
          "|---|---|---|---|---|---|---|---|---|"]
    for a in audits:
        c = a["counts"]
        L.append(f"| {a['ticker']} | {sum(c.values())} | {c['NEAR_LABEL']} | {c['ELSEWHERE']} | {c['NOT_FOUND']} | "
                 f"{len(a['meta_mismatch'])} | {len(a['derived_errors'])} | {len(a['period_issues'])} | "
                 f"{a['columns']['ok']} / {a['columns']['off']} / {a['columns']['na']} |")
    for a in audits:
        t = a["result"].table
        L += ["", f"## {a['ticker']} — {a['name']} (CIK {a['cik']:010d})", ""]
        L += ["| FY label | Period end | Days | Revenue $M | Op. income $M | Op. cash flow $M | Capex $M | FCF $M | Diluted shares (reported, M) | Shares (split-adj., M) |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in t.iloc[::-1].iterrows():
            def cell(metric, value, shares=False):
                if pd.isna(value):
                    return "—"
                return f"{money(value, shares)} {MARK[a['matrix'].get((r['period_end'], metric), 'ERROR')]}"
            L.append(f"| {int(r['fiscal_year']) if pd.notna(r['fiscal_year']) else '?'} | {r['period_end']} | {r['days']} | "
                     f"{cell('revenue', r['revenue'])} | {cell('operating_income', r['operating_income'])} | "
                     f"{cell('operating_cash_flow', r['operating_cash_flow'])} | {cell('capex', r['capex'])} | "
                     f"{money(r['free_cash_flow'])} | {cell('diluted_shares', r['diluted_shares'], True)} | "
                     f"{money(r['diluted_shares_adjusted'], True)} |")
        L += ["", "**Filings used** (form / filing date / period of report as printed on the filing's own SEC index page):", ""]
        for accn, f in sorted(a["filings"].items(), key=lambda kv: kv[1].get("filed", "")):
            if "error" in f:
                L.append(f"- {accn}: could not be downloaded ({f['error']})")
            else:
                L.append(f"- {accn} — {f['form']}, filed {f['filed']}, period {f['period']} — [filing index]({f['index']}) · [document]({f['url']})")
        for title, items in (("Filing-page mismatches", a["meta_mismatch"]), ("Arithmetic errors", a["derived_errors"]),
                             ("Period issues", a["period_issues"]), ("Numbers in the wrong year column", a["column_off"]),
                             ("Restated values (first filing differed from latest)", a["restated"])):
            L += ["", f"**{title}:** " + ("none" if not items else ""), ""]
            L += [f"- {x}" for x in items[:25]]
        if a["result"].notices or a["result"].warnings:
            L += ["", "**App notices/warnings shown for this company:**", ""]
            L += [f"- {x}" for x in a["result"].notices + a["result"].warnings]
        L += ["", "**Blank cells — does the filing itself print a number?**", ""]
        L += ([f"- {g['period_end']} {g['metric']}: " + (f"filing text reads: “{g['snippet']}” ({g['accn']})" if g["snippet"] else f"no matching line found in {g['accn']}") for g in a["gaps"]]
              or ["- none"])
        L += ["", "**10-Q cross-check, latest fiscal year** (9-month year-to-date 10-Q figure; implied Q4 = 10-K year − 9 months):", ""]
        for q in a["tenq"]:
            if "note" in q:
                L.append(f"- {q['metric']}: {q['note']}")
            else:
                L.append(f"- {q['metric']}: FY {q['fy_value'] / 1e6:,.0f}M; 9M YTD {q['ytd9'] / 1e6:,.0f}M (to {q['ytd_end']}, "
                         f"10-Q {q['accn']}, filed {q['filed']}); implied Q4 {q['implied_q4'] / 1e6:,.0f}M; "
                         f"sane={q['sane']}; YTD figure in 10-Q document: {q['check']}")
    path.write_text("\n".join(L) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true", help="ignore the disk cache")
    args = parser.parse_args()

    ticker_map = cached(CACHE / "tickers.json", lambda: sec_client.fetch_ticker_map(), args.refresh, binary_json=True)
    details: List[dict] = []
    audits = []
    for ticker in TICKERS:
        cik = ticker_map[ticker]["cik"]
        facts = cached(CACHE / "companyfacts" / f"{ticker}.json",
                       lambda cik=cik: sec_client.fetch_company_facts(cik), args.refresh, binary_json=True)
        print(f"auditing {ticker} ...", flush=True)
        audits.append(audit_company(ticker, cik, facts, args.refresh, details))

    REPORTS.mkdir(exist_ok=True)
    write_report(audits, REPORTS / "verification_report.md")
    with open(REPORTS / "verification_details.csv", "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(details[0]))
        writer.writeheader()
        writer.writerows(details)
    for a in audits:
        print(a["ticker"], a["counts"], "meta:", len(a["meta_mismatch"]), "arith:", len(a["derived_errors"]),
              "periods:", len(a["period_issues"]), "columns:", a["columns"])
    print("report: reports/verification_report.md")


if __name__ == "__main__":
    main()
